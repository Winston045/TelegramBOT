import { describe, expect, it } from "vitest";
import { banalIn, guardBanal } from "../src/factcheck.js";

describe("общеизвестное в изюминке - брак (редакция 22.11)", () => {
  it("ловит школьные факты о знаменитых событиях", () => {
    for (const q of [
      "Бои за город были тяжелейшими: Красная армия штурмом взяла Берлин 2 мая 1945 года.",
      "Берлин пал 2 мая, а 9 мая 1945 года была подписана капитуляция.",
      "Над Рейхстагом было водружено Знамя Победы.",
      "Сталинградская битва стала коренным переломом в ходе войны.",
      "Под Прохоровкой произошло крупнейшее танковое сражение в истории.",
      "Высадка в Нормандии - крупнейшая морская десантная операция, открывшая второй фронт.",
      "Блокада Ленинграда длилась 872 дня.",
      "Великая Отечественная война началась 22 июня 1941 года.",
    ]) expect(banalIn(q), q).toBeTruthy();
  });
  it("не трогает конкретные малоизвестные детали", () => {
    for (const q of [
      "Т-34 был разработан на Харьковском заводе № 183, до переноса производства на Урал.",
      "Наблюдатели аэростатов получили парашюты раньше лётчиков.",
      "Пушку перевезли на остров по льду Финского залива, разобрав на части.",
      "Берлинская подземка служила укрытием: в туннелях метро прятались тысячи жителей.",
    ]) expect(banalIn(q), q).toBeUndefined();
  });
  it("изюминка из учебника снимается, остаётся место и дата", () => {
    const c = {
      caption: "Советские солдаты на улице Берлина.",
      quote: "Красная армия взяла Берлин 2 мая 1945 года после тяжелейших боёв.",
      quote_place: "Берлин, май 1945 года.",
      quote_kind: "context" as const,
    };
    const v = guardBanal({ caption: c, rewritten: false }, c);
    expect(v.outcome).toBe("quote_dropped");
    expect(v.caption.quote).toBe("Берлин, май 1945 года.");
  });
});

describe("правка существующих постов", async () => {
  const { fixCaption } = await import("../scripts/fix-banal.js");
  it("вырезает общеизвестное предложение, живое и строку места оставляет", () => {
    const html =
      "Работницы в штольнях Инкермана.\n<blockquote expandable>В подземных штольнях работницы шили ушанки и ватники для защитников города, а рядом действовали школа и ясли. Бои за Крым и оборона Севастополя продолжались с 30 октября 1941 года по 4 июля 1942 года.</blockquote>\n<blockquote>Севастополь, 1942 год.</blockquote>\n\n<a href=\"https://t.me/Story_Teams\">STORY | TEAM</a>";
    const out = fixCaption(html);
    expect(out).toContain("школа и ясли.</blockquote>");
    expect(out).not.toContain("продолжались");
    expect(out).toContain("<blockquote>Севастополь, 1942 год.</blockquote>");
  });
  it("цитата целиком из учебника снимается, место и дата остаются", () => {
    const html =
      "Советские солдаты на улице Берлина.\n<blockquote expandable>За 17 дней наступления Красная армия заняла Берлин. Взятие столицы привело к безоговорочной капитуляции Германии.</blockquote>\n<blockquote>Берлин, май 1945 года.</blockquote>\n\n<a href=\"x\">S</a>";
    expect(fixCaption(html)).toBe("Советские солдаты на улице Берлина.\n<blockquote>Берлин, май 1945 года.</blockquote>\n\n<a href=\"x\">S</a>");
  });
});
