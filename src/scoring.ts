import { geminiJson, imagePart } from "./gemini.js";

export type VisionScore = {
  score: number; // 0-100
  tags: {
    period?: string;
    region?: string;
    subject?: string;
    military?: boolean;
    action?: boolean;
  };
  unsafe: boolean;
};

/** Схема полей оценки в JSON-ответе — общая для скоринга и анализа. */
export const SCORE_FIELDS_SCHEMA = `"score": <0-100>, "tags": {"period": "<эпоха, напр. "WW2" | "interwar" | "WW1" | "cold_war">", "region": "<регион, напр. "europe" | "ussr" | "usa" | "asia">", "subject": "<тема одним словом, напр. "armor" | "aviation" | "street" | "portrait" | "navy" | "homefront">", "military": <true|false - война и армия или мирный сюжет>, "action": <true|false - в кадре что-то происходит или это статика/постановка>}, "unsafe": <true|false>`;

/** Критерии оценки — общий блок для скоринга и анализа. */
export const SCORING_CRITERIA = `score отвечает ТОЛЬКО на один вопрос: насколько
хорош и интересен сам снимок. Тип сюжета (движение или постановка, война или
мирная жизнь) на оценку НЕ влияет - для этого есть теги, а порядок публикации
подбирает редакция. Не занижай оценку за то, что кадр постановочный.

Шкала:
- 85-100: событие, которое узнают, или кадр, от которого невозможно
  оторваться: знаменитый момент, редчайшая съёмка, сильнейшая сцена;
- 65-84: хороший архивный кадр - читаемые лица и техника, понятный сюжет,
  есть что разглядывать и о чём рассказать;
- 45-64: обычный архивный снимок: сюжет понятен, но ничем не выделяется;
- 25-44: слабый кадр - мелкие неразличимые фигуры, пустая композиция,
  сюжет ни о чём;
- 0-24: технический брак: нечитаемый скан, сильная засветка или чернота,
  обрезанный кадр, страница документа вместо фотографии, современное фото,
  репродукция картины или плаката, коллаж, кадр не по теме канала.

Что повышает оценку: читаемость деталей (лица, техника, надписи),
выразительность, редкость сюжета, живая эмоция, узнаваемое событие.
Что понижает: мутный или мелкий кадр, невозможность понять, что происходит.

Жёсткое военное содержание (разрушения, пленные, потери) оценку НЕ снижает -
канал о войне без прикрас.

Теги ставь честно, они важнее оценки для подбора ленты:
- military: true, если война и армия (фронт, техника, флот, авиация, тыл
  войны, пленные, разрушения, военачальники); false для мирного сюжета;
- action: true, если в кадре ЧТО-ТО ПРОИСХОДИТ - бой, стрельба, марш,
  погрузка, работа расчёта, взлёт, ремонт, эвакуация, техника в движении,
  пожар, живая сцена. false, если это статика: построение, парад-смотр,
  позирование у машины, портрет, техника выставлена для съёмки, совещание,
  вручение наград, памятник, фасад здания, групповое фото.

unsafe = true, если на снимке: тела погибших, казни, графическое насилие,
нацистская символика крупным планом. Это только пометка для редакторов,
score ставь по общим критериям.`;

const SCORING_PROMPT = `Ты отбираешь исторические фотографии для публичного телеграм-канала
о ВОЕННОЙ ИСТОРИИ: Первая мировая, Вторая мировая, холодная война -
Корея, Вьетнам, Берлинская стена, Афганистан, гонка вооружений.
Оцени снимок и верни строго JSON без пояснений:

{${SCORE_FIELDS_SCHEMA}}

${SCORING_CRITERIA}`;

export async function scoreImage(image: string | Buffer): Promise<VisionScore> {
  const img = await imagePart(image);
  const result = await geminiJson<VisionScore>([{ text: SCORING_PROMPT }, img]);
  return {
    score: Math.max(0, Math.min(100, Math.round(result.score ?? 0))),
    tags: result.tags ?? {},
    unsafe: Boolean(result.unsafe),
  };
}
