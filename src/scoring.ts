import { geminiJson, imagePart } from "./gemini.js";

export type VisionScore = {
  score: number; // 0-100
  tags: { period?: string; region?: string; subject?: string; military?: boolean };
  unsafe: boolean;
};

/** Схема полей оценки в JSON-ответе — общая для скоринга и анализа. */
export const SCORE_FIELDS_SCHEMA = `"score": <0-100>, "tags": {"period": "<эпоха, напр. "WW2" | "interwar" | "WW1" | "cold_war">", "region": "<регион, напр. "europe" | "ussr" | "usa" | "asia">", "subject": "<тема одним словом, напр. "armor" | "aviation" | "street" | "portrait" | "navy" | "homefront">", "military": <true|false - война и армия или мирный сюжет>}, "unsafe": <true|false>`;

/** Критерии оценки — общий блок для скоринга и анализа. */
export const SCORING_CRITERIA = `Критерии score:
- ГЛАВНОЕ — военная тематика: солдаты, техника, фронт, флот, авиация,
  военный тыл, руины войны, парады, пленные, военачальники. Такие сюжеты
  оценивай высоко (60-100 при хорошем кадре);
- целься в снимки, интересные ЛЮБИТЕЛЯМ ИСТОРИИ: редкие моменты, известные
  операции и сражения, необычная или экспериментальная техника, живые сцены
  фронта и тыла, кадры с историей за ними;
- ГЛАВНЫЙ ОТБОР - ДЕЙСТВИЕ. Спрашивай: что происходит в кадре прямо
  сейчас? Если ответ «ничего, все позируют» - это проходной снимок.
    * ЖИВОЕ (65-95): бой, стрельба, атака, погрузка и марш, работа расчёта,
      взлёт и посадка, ремонт под открытым небом, эвакуация раненых,
      техника в движении, пожар, разрушение на глазах, живые эмоции;
    * СТАТИКА (не выше 45, даже если техника редкая): построения, парадные
      шеренги, экипаж позирует у машины, портрет на фоне, техника,
      выставленная для съёмки, генералы за столом, вручение наград,
      групповое фото личного состава.
  Исключение для статики - только если сам предмет уникален: невиданный
  прототип, знаменитый человек в известный момент, редчайший кадр эпохи;
- ценится НЕОБЫЧНОЕ: любопытные детали эпохи, моменты, которые хочется
  разглядывать;
- памятники, мемориальные доски, статичные фасады зданий, церемонии
  открытия табличек — скучно, не выше 35;
- НЕвоенный сюжет допустим, но планка для него ВЫШЕ военной. Спрашивай
  себя: захочет ли человек показать это фото другу? Если да - ставь
  наравне с военными (65-85) и не стесняйся:
    * знаменитый или редкий момент эпохи, который узнают;
    * первое в своём роде: техника, рекорд, испытание, стройка века;
    * сильная человеческая сцена - эмоция, характер, необычное занятие;
    * поразительный или курьёзный сюжет, который сам себя объясняет;
    * по-настоящему красивый кадр: свет, композиция, атмосфера времени.
  Если же кадр «просто был» - улица, фасад, чиновник за столом, групповое
  фото без истории, парадный портрет, туристический вид - это скучно,
  не выше 35, каким бы старым он ни был;
- выразительность кадра и необычность сюжета;
- читаемость деталей (техника, лица, надписи);
- жёсткое военное содержание (разрушения, пленные, потери) НЕ снижает
  оценку — канал о войне без прикрас, отбирают живые редакторы.

unsafe = true, если на снимке: тела погибших, казни, графическое насилие,
нацистская символика крупным планом. Это только пометка для редакторов,
score ставь по общим критериям.`;

const SCORING_PROMPT = `Ты отбираешь исторические фотографии для публичного телеграм-канала
о ВОЕННОЙ ИСТОРИИ: Первая мировая, Вторая мировая, холодная война -
Корея, Вьетнам, Берлинская стена, Афганистан, гонка вооружений.
Оцени снимок и верни строго JSON без пояснений:

{${SCORE_FIELDS_SCHEMA}}

${SCORING_CRITERIA}`;

export async function scoreImage(image: string | Buffer): Promise<VisionScore> {
  const img = await imagePart(image);
  const result = await geminiJson<VisionScore>([{ text: SCORING_PROMPT }, img]);
  return {
    score: Math.max(0, Math.min(100, Math.round(result.score ?? 0))),
    tags: result.tags ?? {},
    unsafe: Boolean(result.unsafe),
  };
}
