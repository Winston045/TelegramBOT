import { geminiJson, imagePart } from "./gemini.js";

export type VisionScore = {
  score: number; // 0-100
  tags: { period?: string; region?: string; subject?: string };
  unsafe: boolean;
};

/** Схема полей оценки в JSON-ответе — общая для скоринга и анализа. */
export const SCORE_FIELDS_SCHEMA = `"score": <0-100>, "tags": {"period": "<эпоха, напр. "WW2" | "interwar" | "WW1" | "cold_war">", "region": "<регион, напр. "europe" | "ussr" | "usa" | "asia">", "subject": "<тема одним словом, напр. "armor" | "aviation" | "street" | "portrait" | "navy" | "homefront">"}, "unsafe": <true|false>`;

/** Критерии оценки — общий блок для скоринга и анализа. */
export const SCORING_CRITERIA = `Критерии score:
- ГЛАВНОЕ — военная тематика: солдаты, техника, фронт, флот, авиация,
  военный тыл, руины войны, парады, пленные, военачальники. Такие сюжеты
  оценивай высоко (60-100 при хорошем кадре);
- целься в снимки, интересные ЛЮБИТЕЛЯМ ИСТОРИИ: редкие моменты, известные
  операции и сражения, необычная или экспериментальная техника, живые сцены
  фронта и тыла, кадры с историей за ними;
- ценится ЖИВОЕ и НЕОБЫЧНОЕ: люди в действии, любопытные детали эпохи,
  моменты, которые хочется разглядывать;
- памятники, мемориальные доски, статичные фасады зданий, церемонии
  открытия табличек — скучно, не выше 35;
- мирная жизнь эпохи — допустимая разбавка, но планка ВЫШЕ военной:
  проходной мирный кадр — не выше 40; 50-70 заслуживает только
  ИСКЛЮЧИТЕЛЬНОЕ - редкий или знаменитый момент, по-настоящему красивый
  кадр, живая сцена, которую хочется разглядывать (рынок, вокзал, цирк,
  стройка века, мода эпохи). Обычная улица или здание - нет;
- выразительность кадра и необычность сюжета;
- читаемость деталей (техника, лица, надписи);
- жёсткое военное содержание (разрушения, пленные, потери) НЕ снижает
  оценку — канал о войне без прикрас, отбирают живые редакторы.

unsafe = true, если на снимке: тела погибших, казни, графическое насилие,
нацистская символика крупным планом. Это только пометка для редакторов,
score ставь по общим критериям.`;

const SCORING_PROMPT = `Ты отбираешь исторические фотографии для публичного телеграм-канала
о ВОЕННОЙ ИСТОРИИ: Первая мировая, Вторая мировая, холодная война.
Оцени снимок и верни строго JSON без пояснений:

{${SCORE_FIELDS_SCHEMA}}

${SCORING_CRITERIA}`;

export async function scoreImage(image: string | Buffer): Promise<VisionScore> {
  const img = await imagePart(image);
  const result = await geminiJson<VisionScore>([{ text: SCORING_PROMPT }, img]);
  return {
    score: Math.max(0, Math.min(100, Math.round(result.score ?? 0))),
    tags: result.tags ?? {},
    unsafe: Boolean(result.unsafe),
  };
}
