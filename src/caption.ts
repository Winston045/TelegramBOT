export type GeneratedCaption = {
  caption: string; // "<b>Подлежащее</b> описание. <i>1945 год.</i>"
  quote: string;
  /** Отдельная вторая цитата «место, дата» - как в эталонных постах 12.2024. */
  quote_place?: string;
  quote_kind: "observation" | "context";
};

