/** Блок метаданных снимка - для промптов анализа (analyze.ts) и критика (critic.ts). */
export function metadataBlock(item: RawItem, extraContext?: string): string {
  const extra = extraContext
    ? `\nДополнительный документальный контекст (тоже источник фактов, за его пределы не выходить):\n${extraContext}\n`
    : "";
  return `Исходные метаданные (язык: ${item.lang}):
- заголовок: ${item.title ?? "(нет)"}
- описание: ${item.description ?? "(нет)"}
- год: ${item.year ?? "(нет)"}
- место: ${item.place ?? "(нет)"}
${extra}`;
}

/** Жёсткие правила подписи - вставляется в промпт анализа. */
export function captionRules(glossary: Record<string, string>): string {
  const glossaryLines = Object.entries(glossary)
    .map(([from, to]) => `  "${from}" → "${to}"`)
    .join("\n");
  return `Жёсткие правила подписи:
1. НЕ ДОБАВЛЯЙ фактов, которых нет во входных данных или не видно на самом фото.
   Нет точной даты - пиши «начало 1943», а не выдумывай число.
2. Топонимы - в названии, актуальном на дату снимка.
3. Глоссарий соблюдать дословно:
${glossaryLines || "  (пусто)"}
4. Исходные описания могут быть пропагандистскими, ошибочными или предвзятыми -
   перепиши нейтрально, оценочные формулировки убери.
5. Формат caption: одно-два ёмких предложения ПРОСТЫМ ТЕКСТОМ.
   Без HTML-тегов, без жирного, без курсива, без markdown.
   Длинное тире не использовать: вместо «—» и «–» всегда обычный дефис «-».
6. ЯЗЫК ЖИВОЙ, а не музейная табличка. Пиши как человек, который сам
   разглядывает снимок и показывает его другу.
   - действие называй глаголом: «расчёт выкатывает орудие на прямую
     наводку», а не «производится перемещение орудия»;
   - канцелярит запрещён: «осуществляется», «производится», «является»,
     «данный», «в ходе проведения», «военнослужащие осуществляют»;
   - штампы подписей запрещены: «на снимке запечатлено», «на фотографии
     изображён», «мы можем видеть», «перед нами»;
   - конкретика вместо общих слов: не «военная техника», а «Т-34-85»;
     не «солдаты одной из частей», а «бойцы 8-й гвардейской армии» -
     но только если это есть в метаданных, иначе просто «бойцы»;
   - не бойся коротких предложений и живых деталей, которые видно в кадре:
     грязь на сапогах, снег на броне, смех, усталые лица;
   - никакого пафоса и оценок: «героические защитники», «легендарный танк»,
     «страшные годы» - убрать. Факт сильнее эпитета.
7. Формат ОБЫЧНОГО поста: caption - описание МАКСИМУМ в два предложения
   БЕЗ даты, а quote - место и год короткой цитатой: «Австрия, 1946 год»,
   «Север СССР, 1941 год.», «Карельский перешеек, 1939 г.»,
   quote_kind: "context". Так выглядит основная масса постов канала.
   Форму даты выбирай живую, как пишут люди: «1946 год», «1939 г.»,
   «Июль - август 1944-го», «сентябрь 1939-го» - не один шаблон в каждом
   посте. Справку и контекст в тело НЕ перекладывать: всё, что не влезло
   в два предложения описания, либо уходит в изюминку (правило 8), либо
   не попадает в пост вовсе. Если ни года, ни места в материале нет -
   caption одной фразой, quote пустой, ничего не выдумывать.
   Года без места быть не должно: когда точного топонима в метаданных нет,
   но принадлежность прямо следует из материала («австро-венгерские
   солдаты», «лагерь армии США», «британская эскадрилья»), ставь в цитату
   страну или фронт - «Австро-Венгрия, 1915 год», «США, 1917 год». Это не
   выдумка, а то же самое, что уже сказано в описании. Голый год цитатой
   («1917 год.») - только если о месте не известно вообще ничего.
8. ИЗЮМИНКА - примерно каждый третий-четвёртый пост, когда материал
   даёт честный интересный факт: судьбу людей или техники, цифру,
   редкую деталь, суть события. Тогда quote - сам факт или развёрнутая
   мини-справка на два-четыре предложения, а место и дата идут НЕ в
   цитату, а в конец caption ОТДЕЛЬНОЙ СТРОКОЙ
   («...в районе Бенгази.\\nЛивия, декабрь 1942 года.») - или, если в
   caption не легли, ОТДЕЛЬНОЙ строкой в quote_place
   («Тихий океан, 1945 год.»). АУДИТОРИЯ КАНАЛА В ТЕМЕ: люди
   разбираются в военной истории, базовые вещи (кто с кем воевал,
   когда шла война, что такое вермахт или люфтваффе) знают и без нас -
   изюминка должна давать знание уровня знатока. Факты СТРОГО из
   метаданных и контекста, ничего не досочинять. Факт виден на самом
   фото - quote_kind: "observation", из материалов - "context".
   КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выдавать за изюминку:
   - опись видимого («на заднем плане...», «слева виден...») без
     объяснения, ЧЕМ это важно или необычно;
   - пересказ caption другими словами;
   - технические сведения о негативе, съёмке, архиве;
   - прописные истины школьного учебника: «Вторая мировая шла с 1939
     по 1945 год», «Сталинград стал переломом в войне» - знающий
     читатель на таком закрывает пост;
   - протокольное перечисление: списки фамилий, должностей, составов
     делегаций и частей без судьбы или смысла. Суть события (что решили,
     что изменилось, чем кончилось) ценнее списка присутствовавших.
   Такое не спасти: тогда пост оформляй ОБЫЧНЫМ (правило 7) - место и
   год в короткой цитате, без псевдофактов.
9. ПОДПИСЬ ПОКАЗЫВАЕТ КРЮЧОК. Тот самый tags.hook, который ты ставишь
   в оценке, - это причина, по которой пост вообще выходит. С неё и
   начинай, а не с общего описания сцены:
   - trophy: чей трофей и у кого захвачен - «Советские танкисты на
     трофейном «Тигре» из 502-го тяжёлого танкового батальона», а не
     «Танкисты возле немецкого танка»;
   - wreck: что именно уничтожено и кем, если это есть в материале -
     «Расстрелянный французский Hotchkiss H38», а не «Танк на обочине»;
   - moment: назови сам момент - «Момент гибели подлодки U-118», а не
     «Подлодка в море»;
   - rare: скажи, чем кадр редок - «Опытный КВ-7 с тремя орудиями»;
   - oddity: назови саму странность - «Снайпер в укрытии под видом
     павшей лошади», а не «Снайпер на позиции»;
   - human: человек и его положение - «Узники Дахау вершат самосуд над
     охранником лагеря»;
   - action: что делают - «Расчёт выкатывает орудие на прямую наводку».
   Если крючок "none", подпись всё равно пиши честно - но такой кадр в
   канал и не пойдёт.`;
}

/**
 * Похоже ли на голые место и год («Италия, 1943 год.») - штатную цитату
 * обычного поста. Используется и сборкой подписи, и редактором цитат.
 */
export function isBarePlaceDate(text: string): boolean {
  const t = text.trim();
  if (t.length === 0 || t.length > 60) return false;
  if (!/(18|19|20)\d{2}/.test(t)) return false;
  const sentences = t.split(/\.\s+/).filter(Boolean);
  return sentences.length <= 2;
}

/** Требует ли лицензия строку атрибуции. PD - нет, CC-BY-* - да. */
export function needsAttribution(license: string): boolean {
  return /cc[- ]by/i.test(license);
}

/** Собирает финальный caption_html: подпись + цитата + атрибуция + подпись канала. */
export function assembleCaptionHtml(
  generated: GeneratedCaption,
  item: Pick<RawItem, "license" | "attribution">,
  channel: AppConfig["channel"],
): string {
  // страховка от «ИИшных» тире: даже если модель ослушалась промпта,
  // в пост уходит обычный дефис
  const dash = (s: string) => s.replace(/[—–]/g, "-");
  // цитата прижата к тексту без пустой строки - так в канале компактнее;
  // единственный двойной перенос остаётся перед футером (его ищет splitFooter)
  // expandable: длинная цитата в канале свёрнута и раскрывается по клику,
  // короткая помещается целиком и выглядит как обычная
  let body = dash(generated.caption);
  // страховка формата: у обычного поста место и год живут в цитате. Если
  // модель оставила quote пустым, а дату влепила последней строкой тела -
  // переносим её в цитату сами, не надеясь на послушность модели
  if (!generated.quote && !generated.quote_place) {
    const lines = body.split("\n");
    const last = lines.length > 1 ? (lines[lines.length - 1] ?? "").trim() : "";
    if (last && isBarePlaceDate(last)) {
      body = lines.slice(0, -1).join("\n");
      return `${body}\n<blockquote expandable>${last}</blockquote>\n\n<a href="${channel.signature_url}">${channel.signature}</a>`;
    }
  }
  if (generated.quote) {
    body += `\n<blockquote expandable>${dash(generated.quote)}</blockquote>`;
    // эталонный формат изюминки: место и дата могут идти отдельной второй
    // цитатой после факта-справки; короткая, поэтому без expandable
    if (generated.quote_place) {
      body += `\n<blockquote>${dash(generated.quote_place)}</blockquote>`;
    }
  } else if (generated.quote_place) {
    // страховка: если модель положила место и дату в quote_place без цитаты,
    // рендерим их обычной цитатой - канонический формат обычного поста
    body += `\n<blockquote expandable>${dash(generated.quote_place)}</blockquote>`;
  }
  // строка атрибуции в пост не идёт - решение редакции (29.07.2026);
  // источник и лицензия сохраняются в базе, у Бундесархива вотермарка в кадре
  return `${body}\n\n<a href="${channel.signature_url}">${channel.signature}</a>`;
}
