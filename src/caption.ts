/** Блок метаданных снимка - для промптов анализа (analyze.ts) и критика (critic.ts). */
export function metadataBlock(item: RawItem, extraContext?: string): string {
  const extra = extraContext
    ? `\nДополнительный документальный контекст (тоже источник фактов, за его пределы не выходить):\n${extraContext}\n`
    : "";
  return `Исходные метаданные (язык: ${item.lang}):
- заголовок: ${item.title ?? "(нет)"}
- описание: ${item.description ?? "(нет)"}
- год: ${item.year ?? "(нет)"}
- место: ${item.place ?? "(нет)"}
${extra}`;
}

/** Жёсткие правила подписи - вставляется в промпт анализа. */
export function captionRules(glossary: Record<string, string>): string {
  const glossaryLines = Object.entries(glossary)
    .map(([from, to]) => `  "${from}" → "${to}"`)
    .join("\n");
  return `Жёсткие правила подписи:
1. НЕ ДОБАВЛЯЙ фактов, которых нет во входных данных или не видно на самом фото.
   Нет точной даты - пиши «начало 1943», а не выдумывай число.
2. Топонимы - в названии, актуальном на дату снимка.
3. Глоссарий соблюдать дословно:
${glossaryLines || "  (пусто)"}
4. Исходные описания могут быть пропагандистскими, ошибочными или предвзятыми -
   перепиши нейтрально, оценочные формулировки убери.
5. Формат caption: одно-два ёмких предложения ПРОСТЫМ ТЕКСТОМ.
   Без HTML-тегов, без жирного, без курсива, без markdown.
   Длинное тире не использовать: вместо «—» и «–» всегда обычный дефис «-».
6. ЯЗЫК ЖИВОЙ, а не музейная табличка. Пиши как человек, который сам
   разглядывает снимок и показывает его другу.
   - действие называй глаголом: «расчёт выкатывает орудие на прямую
     наводку», а не «производится перемещение орудия»;
   - канцелярит запрещён: «осуществляется», «производится», «является»,
     «данный», «в ходе проведения», «военнослужащие осуществляют»;
   - штампы подписей запрещены: «на снимке запечатлено», «на фотографии
     изображён», «мы можем видеть», «перед нами»;
   - конкретика вместо общих слов: не «военная техника», а «Т-34-85»;
     не «солдаты одной из частей», а «бойцы 8-й гвардейской армии» -
     но только если это есть в метаданных, иначе просто «бойцы»;
   - не бойся коротких предложений и живых деталей, которые видно в кадре:
     грязь на сапогах, снег на броне, смех, усталые лица;
   - никакого пафоса и оценок: «героические защитники», «легендарный танк»,
     «страшные годы» - убрать. Факт сильнее эпитета.
7. quote обязателен. Цитата - познавательная часть поста: читатель
   не знает, что за момент на этом снимке, и должен узнать что-то
   новое - это главная её работа. При этом АУДИТОРИЯ КАНАЛА В ТЕМЕ:
   люди разбираются в военной истории, базовые вещи (кто с кем воевал,
   когда шла война, что такое вермахт или люфтваффе) они знают и без
   нас. Новое знание для них - конкретика уровня знатока: судьба именно
   этих людей или техники, цифры, редкая деталь, оперативный контекст
   именно этого момента. Три варианта - как в канале:
   а) ОСНОВНОЙ: есть честный факт (судьба людей или техники, цифры,
      контекст события, редкость момента) - тогда место и дата идут
      в конце caption, лучше ОТДЕЛЬНОЙ СТРОКОЙ после описания
      («...в районе Бенгази.\\nЛивия, декабрь 1942 года.»), а quote -
      сам факт, хотя бы одно предложение. Если факт виден на фото -
      quote_kind: "observation", если из метаданных - "context".
      Если из метаданных и контекста можно честно достать хоть один
      факт - предпочитай этот вариант.
   б) факта нет - в caption дату НЕ писать, quote - только место и дата:
      «Австрия, 1946 год», «Карельский перешеек, 1939 г.»,
      quote_kind: "context". Форму даты выбирай живую, как пишут люди:
      «1946 год», «1939 г.», «Июль - август 1944-го», «сентябрь 1939-го» -
      не один и тот же шаблон в каждом посте.
   в) факт есть, а в тело caption место и дата не легли - положи факт в
      quote, а место и дату ОТДЕЛЬНОЙ строкой в quote_place
      («Тихий океан, 1945 год.»). В остальных случаях quote_place пустой.
   Лучший вариант поста - когда полное описание со страницы архива
   богато фактами: тогда quote делай РАЗВЁРНУТОЙ мини-справкой на два-
   четыре предложения (история события, судьба людей или техники,
   цифры). Факты - строго из описания, ничего не досочинять.
   КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выдавать за интересный факт:
   - опись видимого («на заднем плане...», «слева виден...») без
     объяснения, ЧЕМ это важно или необычно;
   - пересказ caption другими словами;
   - технические сведения о негативе, съёмке, архиве;
   - прописные истины школьного учебника: «Вторая мировая шла с 1939
     по 1945 год», «Сталинград стал переломом в войне» - знающий
     читатель на таком закрывает пост.
   Настоящий, но скромный факт лучше голых места и даты: расскажи его.
   Вариант (б) - последнее прибежище, когда из метаданных и контекста
   честно не достать вообще ничего. Пустышку из списка выше место и
   дата не спасут - но и превращать её в «факт» нельзя.`;
}

/** Требует ли лицензия строку атрибуции. PD - нет, CC-BY-* - да. */
export function needsAttribution(license: string): boolean {
  return /cc[- ]by/i.test(license);
}

/** Собирает финальный caption_html: подпись + цитата + атрибуция + подпись канала. */
export function assembleCaptionHtml(
  generated: GeneratedCaption,
  item: Pick<RawItem, "license" | "attribution">,
  channel: AppConfig["channel"],
): string {
  // страховка от «ИИшных» тире: даже если модель ослушалась промпта,
  // в пост уходит обычный дефис
  const dash = (s: string) => s.replace(/[—–]/g, "-");
  // цитата прижата к тексту без пустой строки - так в канале компактнее;
  // единственный двойной перенос остаётся перед футером (его ищет splitFooter)
  // expandable: длинная цитата в канале свёрнута и раскрывается по клику,
  // короткая помещается целиком и выглядит как обычная
  let body = dash(generated.caption);
  if (generated.quote) {
    body += `\n<blockquote expandable>${dash(generated.quote)}</blockquote>`;
  }
  // эталонный формат: место и дата могут идти отдельной второй цитатой
  // после факта-справки; короткая, поэтому без expandable
  if (generated.quote_place) {
    body += `\n<blockquote>${dash(generated.quote_place)}</blockquote>`;
  }
  // строка атрибуции в пост не идёт - решение редакции (29.07.2026);
  // источник и лицензия сохраняются в базе, у Бундесархива вотермарка в кадре
  return `${body}\n\n<a href="${channel.signature_url}">${channel.signature}</a>`;
}
