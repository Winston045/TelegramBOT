-- Кадры, сорванные лимитом Gemini, считаем отдельно от брака подписи.
--
-- Без этого разбора здоровье прогона врало: 13.08 квота кончилась в
-- середине сбора, до резерва не дошло ни одного кадра, а бот написал
-- «либо все отсеяны как брак, либо не сгенерировались подписи» - и
-- редакция пошла искать поломку в фильтрах, которых там не было.
alter table if exists collect_runs
  add column if not exists quota_failed integer not null default 0;
